async function asegurarCarrera(
  repositorio: Repository<Carrera>,
  datos: { id: string; nombre: string; area: string; imagenUrl: string },
) {
  const existente = await repositorio.findOneBy({ nombre: datos.nombre });
  if (existente !== null) {
    if (existente.area === null || existente.imagenUrl === null) {
      existente.area ??= datos.area;
      existente.imagenUrl ??= datos.imagenUrl;
      return repositorio.save(existente);
    }
    return existente;
  }

  return repositorio.save(repositorio.create(datos));
}

async function asegurarUniversidad(
  repositorio: Repository<Universidad>,
  id: string,
  nombre: string,
  ciudad: string,
  imagenUrl: string,
) {
  const existente = await repositorio.findOneBy({ nombre });
  if (existente !== null) {
    if (existente.imagenUrl === null) {
      existente.imagenUrl = imagenUrl;
      return repositorio.save(existente);
    }
    return existente;
  }

  return repositorio.save(
    repositorio.create({ id, nombre, ciudad, imagenUrl }),
  );
}

export async function sembrarBd(dataSource: DataSource) {
  const carreras = new Map<string, Carrera>();
  for (const carrera of CARRERAS) {
    carreras.set(
      carrera.id,
      await asegurarCarrera(dataSource.getRepository(Carrera), carrera),
    );
  }

  const universidades = new Map<string, Universidad>();
  for (const universidad of UNIVERSIDADES) {
    universidades.set(
      universidad.id,
      await asegurarUniversidad(
        dataSource.getRepository(Universidad),
        universidad.id,
        universidad.nombre,
        universidad.ciudad,
        universidad.imagenUrl,
      ),
    );
  }

  const ofertas = dataSource.getRepository(OfertaAcademica);
  for (const oferta of [...OFERTAS, ...OFERTAS_AMPLIADAS]) {
    const existente = await ofertas.findOneBy({ snies: oferta.snies });
    if (existente !== null) {
      continue;
    }

    const universidad = universidades.get(oferta.universidadId);
    const carrera = carreras.get(oferta.carreraId);
    if (universidad === undefined || carrera === undefined) {
      throw new Error(`Faltan relaciones para la oferta ${oferta.snies}`);
    }

    await ofertas.save(
      ofertas.create({
        id: oferta.id,
        snies: oferta.snies,
        ciudad: oferta.ciudad,
        costo: oferta.costo,
        modalidad: oferta.modalidad,
        jornada: oferta.jornada,
        duracion: oferta.duracion,
        acreditacion: oferta.acreditacion,
        universidad,
        carrera,
      }),
    );
  }

  const usuarios = dataSource.getRepository(Usuario);
  await asegurarUsuario(usuarios, {
    id: IDS_SEMILLA.usuario,
    nombre: 'Nicolas',
    correo: 'nicolas@correo.com',
    clave: '12345678',
    rol: 'estudiante',
    perfil: { apellido: 'Diaz', ciudad: 'Bogota' },
  });
  await asegurarUsuario(usuarios, {
    id: IDS_SEMILLA.admin,
    nombre: 'Admin',
    correo: 'admin@correo.com',
    clave: 'admin12345',
    rol: 'admin',
    perfil: { apellido: 'SAN', ciudad: 'Bogota' },
  });
}

async function asegurarUsuario(
  repositorio: Repository<Usuario>,
  datos: {
    id: string;
    nombre: string;
    correo: string;
    clave: string;
    rol: Rol;
    perfil: { apellido: string; ciudad: string };
  },
) {
  const existente = await repositorio.findOneBy({ correo: datos.correo });
  if (existente === null) {
    await repositorio.save(
      repositorio.create({
        ...datos,
        clave: await bcrypt.hash(datos.clave, 10),
        preferencias: { costo: 3, modalidad: 3, ubicacion: 3, acreditacion: 3 },
      }),
    );
    return;
  }

  // Idempotencia: si la clave del demo quedo en texto plano, se hashea.
  if (!existente.clave.startsWith('$2')) {
    existente.clave = await bcrypt.hash(datos.clave, 10);
  }
  existente.rol = datos.rol;
  await repositorio.save(existente);
}
